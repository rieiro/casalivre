-- Migration 040: platform-bound iCal <-> property URL validation and anti-fraud lock
BEGIN;

ALTER TABLE calendar_feeds
    ADD COLUMN IF NOT EXISTS verification_mode TEXT NOT NULL DEFAULT 'sync_only'
        CHECK (verification_mode IN ('ota', 'sync_only')),
    ADD COLUMN IF NOT EXISTS property_url TEXT NULL,
    ADD COLUMN IF NOT EXISTS canonical_listing_id TEXT NULL,
    ADD COLUMN IF NOT EXISTS ics_metadata TEXT NULL,
    ADD COLUMN IF NOT EXISTS review_status TEXT NOT NULL DEFAULT 'approved'
        CHECK (review_status IN ('approved', 'pending_review', 'rejected')),
    ADD COLUMN IF NOT EXISTS reviewed_by INTEGER NULL REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS review_note TEXT NULL,
    ADD COLUMN IF NOT EXISTS consent_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS verification_ip TEXT NULL;

-- The data backfill runs once (the jumpstart applies all migrations on every boot).
DO $$
DECLARE
    v INTEGER;
BEGIN
    SELECT COALESCE((SELECT NULLIF(value, '')::int FROM schema_meta WHERE skey = 'schema_version'), 0) INTO v;
    IF v < 40 THEN
        -- Legacy verified / pending OTA rows keep the public badge and become OTA mode.
        UPDATE calendar_feeds
           SET verification_mode = 'ota'
         WHERE verified_at IS NOT NULL
            OR (status = 'pending_verification' AND source_platform IN ('airbnb', 'booking', 'vrbo'));

        UPDATE calendar_feeds
           SET review_status = 'approved'
         WHERE verified_at IS NOT NULL;

        UPDATE calendar_feeds f
           SET property_url = COALESCE(f.property_url, pev.public_url),
               canonical_listing_id = COALESCE(f.canonical_listing_id, pev.canonical_listing_id),
               ics_metadata = COALESCE(f.ics_metadata, pev.ics_metadata)
          FROM property_external_verifications pev
         WHERE pev.property_id = f.property_id
           AND pev.ical_url_hash IS NOT NULL
           AND pev.ical_url_hash = f.url_hash;
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_calendar_feeds_canonical
    ON calendar_feeds (canonical_listing_id)
    WHERE canonical_listing_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_calendar_feeds_canonical_non_booking
    ON calendar_feeds (canonical_listing_id)
    WHERE canonical_listing_id IS NOT NULL AND source_platform <> 'booking';

CREATE INDEX IF NOT EXISTS idx_calendar_feeds_pending_review
    ON calendar_feeds (review_status, verified_at)
    WHERE review_status = 'pending_review';

-- Permanent ledger: survives property deletion (property_id becomes nullable ON DELETE SET NULL).
ALTER TABLE ota_credit_ledger ADD COLUMN IF NOT EXISTS canonical_listing_id TEXT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'ota_credit_ledger' AND column_name = 'id') THEN
        ALTER TABLE ota_credit_ledger DROP CONSTRAINT IF EXISTS ota_credit_ledger_pkey;
        ALTER TABLE ota_credit_ledger ADD COLUMN id INTEGER GENERATED BY DEFAULT AS IDENTITY;
        ALTER TABLE ota_credit_ledger ADD PRIMARY KEY (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'ota_credit_ledger'::regclass AND contype = 'p'
    ) THEN
        ALTER TABLE ota_credit_ledger ADD PRIMARY KEY (id);
    END IF;
    ALTER TABLE ota_credit_ledger ALTER COLUMN property_id DROP NOT NULL;
    ALTER TABLE ota_credit_ledger DROP CONSTRAINT IF EXISTS ota_credit_ledger_property_id_fkey;
    ALTER TABLE ota_credit_ledger
        ADD CONSTRAINT ota_credit_ledger_property_id_fkey
        FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE SET NULL;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_ota_credit_ledger_property
    ON ota_credit_ledger (property_id)
    WHERE property_id IS NOT NULL;

-- Backfill the canonical id from the legacy verification or the matching feed.
UPDATE ota_credit_ledger l
   SET canonical_listing_id = COALESCE(
       (SELECT pev.canonical_listing_id FROM property_external_verifications pev
         WHERE pev.property_id = l.property_id AND pev.canonical_listing_id IS NOT NULL LIMIT 1),
       (SELECT f.canonical_listing_id FROM calendar_feeds f
         WHERE f.property_id = l.property_id AND f.canonical_listing_id IS NOT NULL LIMIT 1)
   )
 WHERE l.canonical_listing_id IS NULL;

-- Keep one credit row per canonical before the unique index.
WITH ranked AS (
    SELECT id, row_number() OVER (PARTITION BY canonical_listing_id ORDER BY awarded_at, id) AS rn
      FROM ota_credit_ledger
     WHERE canonical_listing_id IS NOT NULL
)
DELETE FROM ota_credit_ledger WHERE id IN (SELECT id FROM ranked WHERE rn > 1);

CREATE UNIQUE INDEX IF NOT EXISTS uq_ota_credit_ledger_canonical
    ON ota_credit_ledger (canonical_listing_id)
    WHERE canonical_listing_id IS NOT NULL;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'casalivre_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON calendar_feeds TO casalivre_app;
        GRANT SELECT, INSERT, UPDATE, DELETE ON ota_credit_ledger TO casalivre_app;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO casalivre_app;
    END IF;
END
$$;

INSERT INTO schema_meta (skey, value)
VALUES ('schema_version', '40')
ON CONFLICT (skey) DO UPDATE SET value = '40';

COMMIT;
