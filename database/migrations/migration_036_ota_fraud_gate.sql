-- Migration 036: OTA fraud-prevention gate, credit ledger and passive downgrade
BEGIN;

ALTER TABLE property_external_verifications
    ADD COLUMN IF NOT EXISTS canonical_listing_id TEXT NULL,
    ADD COLUMN IF NOT EXISTS ical_url_hash TEXT NULL
        CHECK (ical_url_hash IS NULL OR ical_url_hash ~ '^[a-f0-9]{64}$'),
    ADD COLUMN IF NOT EXISTS ics_metadata TEXT NULL,
    ADD COLUMN IF NOT EXISTS fail_count SMALLINT NOT NULL DEFAULT 0
        CHECK (fail_count >= 0),
    ADD COLUMN IF NOT EXISTS last_passive_check_at TIMESTAMPTZ NULL;

-- Data migration: hash existing feeds and give existing rows a canonical id.
UPDATE property_external_verifications
   SET ical_url_hash = encode(sha256(convert_to(ical_url, 'UTF8')), 'hex')
 WHERE ical_url IS NOT NULL AND ical_url_hash IS NULL;

UPDATE property_external_verifications
   SET canonical_listing_id = platform || ':' || public_url
 WHERE canonical_listing_id IS NULL;

DROP INDEX IF EXISTS uq_pev_verified_ical_url;

CREATE UNIQUE INDEX IF NOT EXISTS uq_pev_ical_url_hash
    ON property_external_verifications (ical_url_hash)
    WHERE ical_url_hash IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_pev_canonical_listing
    ON property_external_verifications (canonical_listing_id)
    WHERE canonical_listing_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS ota_credit_ledger (
    property_id     INTEGER PRIMARY KEY REFERENCES properties(id) ON DELETE CASCADE,
    user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    verification_id INTEGER NULL,
    credits         INTEGER NOT NULL CHECK (credits > 0),
    awarded_at      TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
);

INSERT INTO ota_credit_ledger (property_id, user_id, verification_id, credits, awarded_at)
SELECT pev.property_id, p.user_id, MIN(pev.id), 5,
       COALESCE(MIN(pev.verified_at), statement_timestamp())
  FROM property_external_verifications pev
  JOIN properties p ON p.id = pev.property_id
 WHERE pev.credits_awarded = 1
 GROUP BY pev.property_id, p.user_id
ON CONFLICT (property_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS ota_challenge_attempts (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
    platform    TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
);

CREATE INDEX IF NOT EXISTS idx_oca_user_created
    ON ota_challenge_attempts (user_id, created_at);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'casalivre_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE
            ON property_external_verifications, ota_credit_ledger, ota_challenge_attempts
            TO casalivre_app;
    END IF;
END
$$;

INSERT INTO schema_meta (skey, value)
VALUES ('schema_version', '36')
ON CONFLICT (skey) DO UPDATE SET value = '36';

COMMIT;
