-- Log de BI/segurança. id (UUIDv7) e created_at (UTC, microssegundos) vêm do PHP.
CREATE TABLE audit.activity_log (
    id                uuid        NOT NULL,
    created_at        timestamptz NOT NULL,
    code              smallint    NOT NULL,
    retention_class   text        NOT NULL CHECK (retention_class IN ('security', 'other')),
    subtype           text        NULL CHECK (length(subtype) <= 32),
    actor_kind        text        NOT NULL CHECK (actor_kind IN ('user', 'anon', 'system')),
    actor_ref         bytea       NULL CHECK (octet_length(actor_ref) = 32),   -- HMAC-SHA256(LOG_SALT[v], "user\0" || id)
    actor_key_version smallint    NULL,
    access_event_id   uuid        NULL,                                        -- sem FK (SVU §1.4 #3)
    payload           jsonb       NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(payload) = 'object'),
    before_value      jsonb       NULL,
    after_value       jsonb       NULL,
    CHECK ((actor_kind = 'user') = (actor_ref IS NOT NULL)),
    CHECK ((actor_ref IS NULL) = (actor_key_version IS NULL)),
    CHECK (retention_class <> 'security' OR access_event_id IS NOT NULL OR actor_kind = 'system'),   -- V-4
    CHECK (octet_length(payload::text) + coalesce(octet_length(before_value::text), 0)
           + coalesce(octet_length(after_value::text), 0) <= 4096),
    PRIMARY KEY (id, retention_class, created_at),
    FOREIGN KEY (code, retention_class) REFERENCES public.activity_actions (code, retention_class)
) PARTITION BY LIST (retention_class);
