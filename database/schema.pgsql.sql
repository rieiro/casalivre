-- Lugares da busca (ADR 001 §11 / §11.2). Substitui cities. name_fold e place_search_keys.key usam
-- COLLATE "C" (prefixo no btree, sem unaccent). places_root_uk do §11.4 (UNIQUE type, name_fold nas raízes)
-- não entra: cities.json tem o mesmo name_fold em UFs diferentes.
CREATE TABLE IF NOT EXISTS places (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL CHECK (type IN ('region', 'city', 'neighborhood', 'poi')),
    parent_id INTEGER REFERENCES places(id) ON DELETE RESTRICT,
    name TEXT NOT NULL,
    name_fold TEXT COLLATE "C" NOT NULL,
    label TEXT NOT NULL,
    uf CHAR(2) NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    bbox_s DOUBLE PRECISION,
    bbox_w DOUBLE PRECISION,
    bbox_n DOUBLE PRECISION,
    bbox_e DOUBLE PRECISION,
    popularity INTEGER NOT NULL DEFAULT 0,
    category TEXT NULL CHECK (category IN (
        'beach', 'waterfall', 'airport', 'national_park', 'protected_area', 'nature_reserve',
        'park', 'lake', 'lagoon', 'bay', 'peak', 'theme_park', 'zoo', 'aquarium', 'viewpoint', 'monument', 'fort'
    )),
    osm_ref TEXT NULL,
    wikidata TEXT NULL,
    CHECK (type = 'poi' OR (category IS NULL AND osm_ref IS NULL AND wikidata IS NULL)),
    CHECK (lat BETWEEN -90 AND 90 AND lng BETWEEN -180 AND 180),
    CHECK (
        (bbox_s IS NULL AND bbox_w IS NULL AND bbox_n IS NULL AND bbox_e IS NULL)
        OR (
            bbox_s IS NOT NULL AND bbox_w IS NOT NULL AND bbox_n IS NOT NULL AND bbox_e IS NOT NULL
            AND bbox_s <= bbox_n AND bbox_w <= bbox_e
        )
    ),
    CHECK (((type = 'city') = (parent_id IS NULL)) OR type = 'region'),
    CHECK (parent_id IS DISTINCT FROM id)
);
CREATE INDEX IF NOT EXISTS idx_places_name_fold ON places (name_fold);
CREATE INDEX IF NOT EXISTS idx_places_parent ON places (parent_id);
CREATE UNIQUE INDEX IF NOT EXISTS places_child_uk ON places (parent_id, type, name_fold) WHERE parent_id IS NOT NULL;
-- Substitui o places_root_uk do ADR (UNIQUE (type, name_fold) nas raízes), que rejeitava homônimos entre UFs.
CREATE UNIQUE INDEX IF NOT EXISTS places_city_uf_uk
  ON places (uf, name_fold) WHERE type = 'city';

