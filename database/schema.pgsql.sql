-- Legal holds e execuções de purga (SVU §2.3). Um hold aberto em subject_type='user' segura as linhas do log com o
-- actor_ref desse usuário (o job recalcula o HMAC em todas as key_version ativas).
CREATE TABLE IF NOT EXISTS legal_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_kind TEXT NOT NULL CHECK (hold_kind IN ('legal_hold', 'judicial', 'cautelar_mci')),
    subject_type TEXT NOT NULL CHECK (subject_type IN ('user', 'booking', 'property', 'org', 'access')),
    subject_id BIGINT NOT NULL,
    case_ref TEXT NOT NULL CHECK (length(case_ref) BETWEEN 1 AND 64),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    opened_by INTEGER NULL REFERENCES users(id) ON DELETE SET NULL,
    expires_at TIMESTAMPTZ NULL,
    closed_at TIMESTAMPTZ NULL,
    closed_by INTEGER NULL REFERENCES users(id) ON DELETE SET NULL,
    CHECK (hold_kind <> 'cautelar_mci' OR (expires_at IS NOT NULL
        AND expires_at <= ((opened_at AT TIME ZONE 'UTC') + interval '60 days') AT TIME ZONE 'UTC')),
    CHECK (closed_at IS NULL OR closed_at >= opened_at),
    UNIQUE (subject_type, subject_id, case_ref)
);
CREATE INDEX IF NOT EXISTS legal_holds_open ON legal_holds (subject_type, subject_id) WHERE closed_at IS NULL;
CREATE TABLE IF NOT EXISTS legal_hold_access_events (
    hold_id BIGINT NOT NULL REFERENCES legal_holds(id) ON DELETE RESTRICT,
    access_event_id UUID NOT NULL,                  -- sem FK (access_log particionado; órfã aceita)
    PRIMARY KEY (hold_id, access_event_id)
);
CREATE INDEX IF NOT EXISTS legal_hold_access_events_ev ON legal_hold_access_events (access_event_id);
